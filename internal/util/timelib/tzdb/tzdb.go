// Package tzdb is the time zone database mongod resolves time zone names
// with: timelib's built-in database, not the host's tzdata. It accepts
// exactly the names mongod accepts and gives the same rules, regardless of
// the host or Go's embedded tzdata.
//
// tzdb.bin and index.go are generated by gen.go.
package tzdb

import (
	_ "embed"
	"sync"
	"time"
)

//go:embed tzdb.bin
var data []byte

type entry struct {
	name         string
	offset, size int
}

var (
	cache  sync.Map // name -> *time.Location
	byName = sync.OnceValue(func() map[string]entry {
		m := make(map[string]entry, len(index))
		for _, e := range index {
			m[e.name] = e
		}
		return m
	})
)

// Load returns the zone named name, matched exactly.
func Load(name string) (*time.Location, bool) {
	if loc, ok := cache.Load(name); ok {
		return loc.(*time.Location), true
	}
	e, ok := byName()[name]
	if !ok {
		return nil, false
	}
	loc, err := time.LoadLocationFromTZData(name, data[e.offset:e.offset+e.size])
	if err != nil {
		return nil, false
	}
	actual, _ := cache.LoadOrStore(name, loc)
	return actual.(*time.Location), true
}
