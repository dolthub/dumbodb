//go:build ignore

// gen converts timelib's built-in time zone database, as compiled into
// mongod, into tzdb.bin and index.go.
//
// Usage, from this directory:
//
//	go run gen.go <path to src/third_party/timelib/dist/timezonedb.h>
//
// Take timezonedb.h from the mongodb/mongo tag DumboDB is tested against.
// mongod compiles the full (not TIMELIB_SUPPORT_SLIM_FILE) variant.
package main

import (
	"bytes"
	"encoding/binary"
	"fmt"
	"os"
	"regexp"
	"strconv"
	"strings"
)

var (
	indexEntry = regexp.MustCompile(`\{ \(char\*\) "([^"]+)"\s*, 0x([0-9A-Fa-f]+) \}`)
	dataByte   = regexp.MustCompile(`0x([0-9A-Fa-f]{2})`)
	version    = regexp.MustCompile(`timezonedb_builtin = \{ "([^"]+)"`)
)

func main() {
	src, err := os.ReadFile(os.Args[1])
	check(err)
	text := string(src)

	full := text[strings.Index(text, "#else"):]
	idxStart := strings.Index(full, "timezonedb_idx_builtin")
	dataStart := strings.Index(full, "timelib_timezone_db_data_builtin")
	entries := indexEntry.FindAllStringSubmatch(full[idxStart:dataStart], -1)

	body := full[dataStart:]
	body = body[strings.Index(body, "{")+1 : strings.Index(body, "};")]
	var data []byte
	for _, m := range dataByte.FindAllStringSubmatch(body, -1) {
		b, err := strconv.ParseUint(m[1], 16, 8)
		check(err)
		data = append(data, byte(b))
	}

	var out bytes.Buffer
	var index strings.Builder
	for i, e := range entries {
		start, err := strconv.ParseUint(e[2], 16, 32)
		check(err)
		end := uint64(len(data))
		if i+1 < len(entries) {
			end, err = strconv.ParseUint(entries[i+1][2], 16, 32)
			check(err)
		}
		record := append([]byte(nil), data[start:end]...)
		if !bytes.HasPrefix(record, []byte("PHP2")) {
			panic(fmt.Sprintf("%s: not a PHP2 record", e[1]))
		}
		// The PHP2 preamble has the size of a TZif header; the rest is TZif
		// followed by timelib's location data, which Go would read as part
		// of the footer.
		copy(record, append([]byte("TZif2"), make([]byte, 15)...))
		record = record[:tzifLength(e[1], record)]
		fmt.Fprintf(&index, "\t{%q, %d, %d},\n", e[1], out.Len(), len(record))
		out.Write(record)
	}

	check(os.WriteFile("tzdb.bin", out.Bytes(), 0o644))

	ver := version.FindStringSubmatch(text)[1]
	license, err := os.ReadFile("gen.go")
	check(err)
	goSrc := string(license[:bytes.Index(license, []byte("//go:build"))]) +
		"// Code generated by gen.go from timelib's timezonedb.h; DO NOT EDIT.\n\npackage tzdb\n\n" +
		"// Version is timelib's version of the database.\n" +
		fmt.Sprintf("const Version = %q\n\n", ver) +
		"var index = []entry{\n" + index.String() + "}\n"
	check(os.WriteFile("index.go", []byte(goSrc), 0o644))
	fmt.Printf("%d zones, %d bytes, version %s\n", len(entries), out.Len(), ver)
}

// tzifLength returns the length of the TZif v2 data at the start of record:
// the 32-bit block, the 64-bit block and the newline-delimited footer.
func tzifLength(name string, record []byte) int {
	blockEnd := func(start int, timeSize int) int {
		count := func(i int) int { return int(binary.BigEndian.Uint32(record[start+20+4*i:])) }
		isutcnt, isstdcnt, leapcnt, timecnt, typecnt, charcnt := count(0), count(1), count(2), count(3), count(4), count(5)
		return start + 44 + timecnt*timeSize + timecnt + typecnt*6 + charcnt + leapcnt*(timeSize+4) + isstdcnt + isutcnt
	}
	v2 := blockEnd(0, 4)
	if !bytes.HasPrefix(record[v2:], []byte("TZif")) {
		panic(fmt.Sprintf("%s: no 64-bit block", name))
	}
	footer := blockEnd(v2, 8)
	if record[footer] != '\n' {
		panic(fmt.Sprintf("%s: no footer", name))
	}
	end := bytes.IndexByte(record[footer+1:], '\n')
	if end < 0 {
		panic(fmt.Sprintf("%s: unterminated footer", name))
	}
	return footer + 1 + end + 1
}

func check(err error) {
	if err != nil {
		panic(err)
	}
}
